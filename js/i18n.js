export function t(key, vars) {
  const lang = state.lang || 'it';
  let str = (dict[lang] && dict[lang][key]) ?? dict.it[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
  }
  return str;
}

